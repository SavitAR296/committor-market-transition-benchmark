r"""Cross-document numbering without xr: reads ../manuscript/{supplement,main}.aux and writes supp_labels.tex (the
supplemental table numbers used by main.tex through \Sref{key}) and main_labels.tex (main-text equation, figure, table
and theorem numbers used by supplement.tex through \Mref{key}).  Both files are plain TeX and travel with the sources."""
import re
from pathlib import Path
MS = Path(__file__).resolve().parents[2] / 'manuscript'
LAB = re.compile(r'\\newlabel\{([^}]*)\}\{\{([^}]*)\}')


def labels(aux):
    p = MS / aux
    return {} if not p.exists() else {k: v for k, v in LAB.findall(p.read_text(errors='ignore')) if not k.endswith('@cref')}


def main():
    s = {k[len('tab:S-'):]: v for k, v in labels('supplement.aux').items() if k.startswith('tab:S-')}
    m = labels('main.aux')
    (MS / 'supp_labels.tex').write_text('% generated by reproducibility_pre/scripts/sync_labels.py -- do not edit\n' +
        ''.join(f'\\expandafter\\def\\csname supp@{k}\\endcsname{{{v}}}\n' for k, v in sorted(s.items())))
    (MS / 'main_labels.tex').write_text('% generated by reproducibility_pre/scripts/sync_labels.py -- do not edit\n' +
        ''.join(f'\\expandafter\\def\\csname main@{k}\\endcsname{{{v}}}\n' for k, v in sorted(m.items()) if re.match(r'^(eq|fig|tab|prop|lem|cor|sec|app):', k)))
    print(f'{len(s)} supplemental tables, {len(m)} main labels')


if __name__ == '__main__':
    main()
